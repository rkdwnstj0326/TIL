def get_subject_totals(scores):
    result = []
    for i in range(len(scores[0])):
        total = 0 # 과목 하나의 총점을 뜻함 total이. so total을 과목이 바뀔 때 0으로 돌아가야댐
        # 두 학생의 리스트를 하나씩 보는 반복문이 필요하다
        for score in scores: #학생리스트 하나씩 꺼냄
            total = total + score[i]
            
        result.append(total)

    return result


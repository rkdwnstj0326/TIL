def find_positions(shelf, target):
    result = []

    for i_shelf in range(len(shelf)): 
        for s in range(len(shelf[0])):
            #여기서 막혔어요. 조건문으로 어떻게 값을 꺼내야할지 감이 안잡혀요 지금
            # shelf에서 i_shelf층의 s번째 값을 꺼내는 표현을 if 왼쪽에 넣어라 -> 지피티의말
            if shelf[i_shelf][s] == target: 
                #shelf[i_shelf][s] 이걸 생각을 못해서 지피티 돌려봣어요

                result.append((i_shelf, s))

    return result



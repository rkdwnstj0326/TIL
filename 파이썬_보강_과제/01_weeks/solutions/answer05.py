'''
문제 05 정답 및 해설 - analyze_scores      [조합: 중첩 + 카운팅 + 탐색]
========================================================================
[출제 의도]
  '새로운 유형'처럼 보이지만 실은 2번(카운팅) + 3번(탐색)을 중첩 반복문
  안에서 동시에 돌리는 것뿐임을 확인시키는 문제.
  시작값이 다른 두 변수(count=0, highest=첫 값)를 한 함수 안에서 함께
  다루게 하여, 3번에서 배운 원리가 우연이 아니었음을 굳힌다.

  실제 1회차 평가 문제 05(count_items), 06(sum_row_maximums)이 2차원
  리스트였고, 09(manage_inventory)가 튜플 반환이었다. 세 요소를 한 문제로
  압축한 형태다.
========================================================================
'''

# ------------------------------------------------------------
# [기본 9점] 제한 내장 함수(max, len, sum) 사용
# ------------------------------------------------------------
def analyze_scores_builtin(classes):
    fail_count = 0
    highest = classes[0][0]
    for scores in classes:
        for score in scores:
            if score < 60:
                fail_count += 1
        highest = max(highest, max(scores))
    return (fail_count, highest)


# ------------------------------------------------------------
# [가산 12점] 제한 내장 함수 미사용, 반복문 직접 구현
# ------------------------------------------------------------
def analyze_scores_manual(classes):
    fail_count = 0              # 아직 아무도 안 셌으므로 0
    highest = classes[0][0]     # 첫 학생의 점수를 잠정 1등으로
    for scores in classes:
        for score in scores:
            if score < 60:
                fail_count += 1
            if score > highest:
                highest = score
    return (fail_count, highest)


analyze_scores = analyze_scores_manual


'''
[모범 설계 주석]
------------------------------------------------------------------------
0-1. [과락 인원 변수의 시작값] 0
     [왜]  아직 한 명도 세지 않았으므로 0. 과락자가 없으면 0이 그대로
           남아야 하는데, 그것이 정답이기도 하다. (2번과 동일한 논리)

0-2. [최고점 변수의 시작값] classes[0][0], 즉 첫 번째 반의 첫 학생 점수
     [왜]  0으로 두면 모든 점수가 0보다 낮은 경우 갱신이 한 번도 일어나지
           않는다. 이번 문제는 점수가 0 이상이라 우연히 통과하지만,
           3번(기온)처럼 음수가 섞이면 즉시 깨지는 방식이다.
           '우연히 맞는 코드'를 쓰지 않기 위해 실제 존재하는 값으로 시작한다.
           같은 이유로 하나는 0, 하나는 첫 원소인 것이지, 규칙이
           제각각인 게 아니다. 결과의 성격이 다르기 때문이다.

1. [무엇을] 바깥 for로 반(scores)을 하나씩 꺼낸다.
   [왜]     classes의 원소가 리스트라서, 한 겹만 돌면 점수가 아니라
            리스트가 나온다. 점수에 닿으려면 한 겹 더 들어가야 한다.

2. [무엇을] 안쪽 for로 그 반의 점수를 하나씩 꺼낸다.
   [왜]     반마다 인원이 달라서 몇 명인지 미리 알 수 없다.
            for는 개수를 몰라도 끝까지 돌기 때문에 이 구조에 맞다.

3. [무엇을] 점수가 60 미만이면 fail_count에 1을 더한다.
   [왜]     '미만'이므로 < 를 쓴다. <= 로 쓰면 예시_03에서 60점 두 명이
            과락으로 잘못 세어져 답이 3이 된다.

4. [무엇을] 같은 자리에서 점수가 highest보다 크면 highest를 갱신한다.
   [왜]     두 작업 모두 '모든 점수를 한 번씩 본다'는 조건이 같으므로,
            반복문을 두 번 돌 필요 없이 한 번에 처리할 수 있다.

5. [무엇을] 반복이 모두 끝난 뒤 (fail_count, highest)를 튜플로 반환한다.
   [왜]     지문이 두 값을 튜플로 묶어 달라고 했다. 리스트로 반환하면
            형식이 달라 오답이다. return 두 개를 쓰면 첫 번째에서 끝난다.
------------------------------------------------------------------------


[추가 질문 모범 답안]
------------------------------------------------------------------------
  Q1. 반복문이 몇 겹 필요한가?
  A1. 2겹. classes의 원소가 리스트여서 한 겹으로는 점수에 닿지 못한다.

  Q2. 앞의 어떤 문제들의 조합인가?
  A2. 2번(카운팅) + 3번(탐색). 여기에 반복문이 한 겹 더 있을 뿐이다.
      => 이 답을 스스로 쓴 학생은 유형 ③에서 벗어나기 시작한 것으로 본다.
         못 쓴 학생에게는 2, 3번 코드와 나란히 놓고 비교시킬 것.
------------------------------------------------------------------------


[자주 나오는 오답 패턴]
------------------------------------------------------------------------
(1) 반복문 한 겹만 사용
    for score in classes:
        if score < 60:          # TypeError (리스트 < 정수)
    => 2차원 구조 인식 실패. 가장 많이 나오는 오답.

(2) highest = 0
    => 이번 데이터에서는 통과하지만 논리적으로 틀림.
       [왜] 칸을 확인해 '왜 안전한지'를 설명 못 하면 감점 처리.
       설명하지 못한 채 맞은 것은 3번에서 이미 틀렸던 것과 같은 상태다.

(3) <= 60 사용
    => 예시_03에서 (3, 60) 반환 (기댓값 (1, 60)). '미만' 오독.

(4) 리스트로 반환
    return [fail_count, highest]
    => 형식 불일치. 평가 유의사항 10번에 의해 오답.

(5) return이 안쪽 for 안에 위치
    => 첫 학생만 처리하고 종료. (0, 85) 반환.

(6) highest 갱신을 바깥 for에만 배치
    for scores in classes:
        if scores > highest:    # 리스트와 정수 비교 => TypeError
    => 어느 층위에서 무엇을 다루는지 혼동. 손 추적표의 '바깥/안쪽' 열이
       바로 이걸 잡기 위한 장치다.
------------------------------------------------------------------------
'''

# ---- 검증 ----
print(analyze_scores([[85, 42, 90], [55, 100], [70]]))  # (2, 100)
print(analyze_scores([[30]]))                           # (1, 30)
print(analyze_scores([[60, 60], [59]]))                 # (1, 60)

'''
문제 02 정답 및 해설 - count_late_days                   
========================================================================
[출제 의도]
  누적과 카운팅은 골격 모양이 거의 같다. 차이는 '무엇을 더하는가' 하나뿐.
      누적   : total += 꺼낸 값      (값 자체를 더함)
      카운팅 : count += 1            (조건이 참일 때 1만 더함)
  이 차이를 언어화하지 못하는 학생은 두 골격을 하나로 뭉뚱그려 외우고 있는
  상태이며, 조건이 붙는 순간 무너진다.
========================================================================
'''

# ------------------------------------------------------------
# [기본 9점] 제한 내장 함수(count) 사용
# ------------------------------------------------------------
def count_late_days_builtin(records):
    return records.count('late')


# ------------------------------------------------------------
# [가산 12점] count / len 미사용, 반복문 직접 구현
# ------------------------------------------------------------
def count_late_days_manual(records):
    count = 0
    for status in records:
        if status == 'late':
            count += 1
    return count


count_late_days = count_late_days_manual


'''
[모범 설계 주석 ]
------------------------------------------------------------------------
1. [무엇을] count 변수를 0으로 만들고 시작한다.
   [왜]     아직 한 건도 세지 않았기 때문. '센 것이 없다'가 곧 0이다.
            지각이 하나도 없으면 반복문이 다 돌아도 0이 남는데,
            예시_02의 기댓값이 0이므로 이 초기값이 맞다.

2. [무엇을] records를 for로 하나씩 꺼낸다.
   [왜]     모든 날의 기록을 빠짐없이 확인해야 개수가 정확해진다.
            중간에 멈추면 뒤쪽 지각을 놓친다.

3. [무엇을] 꺼낸 값이 'late'인지 if로 판정한다.
   [왜]     1번 문제는 모든 값을 무조건 더했지만, 여기는 '지각인 것만'
            세야 한다. 즉 골격은 같고 조건이 하나 추가된 것이다.

4. [무엇을] 조건이 참일 때만 count에 1을 더한다.
   [왜]     세는 대상은 '값'이 아니라 '건수'다. 'late'라는 문자열은
            더할 수 없고, 몇 번 나왔는지가 궁금한 것이므로 1씩 더한다.
            여기서 status를 더하면 TypeError가 난다.
------------------------------------------------------------------------


[추가 질문 모범 답안]
------------------------------------------------------------------------
  Q. 1번(누적)과 골격이 거의 같은데 무엇이 다른가?
  A. 1번은 꺼낸 값 자체를 더하고(total += price),
     2번은 조건이 맞을 때 1만 더한다(count += 1).
     또 1번에는 if가 없고 2번에는 있다.
     => 이 답을 못 쓰면 두 골격을 구분 못 하고 외운 상태.
------------------------------------------------------------------------


[자주 나오는 오답 패턴]
------------------------------------------------------------------------
(1) count += status
    => TypeError. 누적과 카운팅을 구분하지 못한 전형적 사례.

(2) if status == 'late':
        count = 1               # 갱신이 아니라 대입 => 항상 1
    => 결과가 1로 나와서 '거의 맞았다'고 착각하기 쉬움. 손 추적표 필수.

(3) if status = 'late':         # SyntaxError
    => 비교(==)와 대입(=) 혼동. 평가에서 Syntax Error는 0점 처리 대상.

(4) return을 if 블록 안에 배치
    => 첫 'late'에서 함수 종료. 항상 1 반환.

(5) 'late' in status 로 판정
    => 이 데이터에서는 우연히 맞지만, 'latest' 같은 값이 오면 깨진다.
       '우연히 통과하는 코드'의 위험성
------------------------------------------------------------------------
'''

# ---- 검증 ----
print(count_late_days(['present', 'late', 'absent', 'late', 'present']))  # 2
print(count_late_days(['present', 'present']))                           # 0
print(count_late_days([]))                                               # 0

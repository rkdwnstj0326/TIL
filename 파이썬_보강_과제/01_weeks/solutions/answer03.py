'''
문제 03 정답 및 해설 - find_hottest_day                    
========================================================================
[출제 의도]  ★ 이번 주 과제의 핵심 문제
  1, 2번에서 학습한 '시작값은 0'을 그대로 적용하면 예시_03에서 틀린다.
  즉, 규칙을 '왜' 없이 외운 학생만 정확히 걸러지도록 설계했다.

  실제 1회차 평가 문제 04(find_price_range), 06(sum_row_maximums)이
  모두 이 함정을 갖고 있었고, 06은 지문에 '음수 포함 가능'을 명시했다.
  같은 함정을 축소판으로 미리 밟게 하는 문제.
========================================================================
'''

# ------------------------------------------------------------
# [기본 9점] 제한 내장 함수(max, index) 사용
# ------------------------------------------------------------
def find_hottest_day_builtin(temps):
    return temps.index(max(temps))


# ------------------------------------------------------------
# [가산 12점] max / index 미사용, 반복문 직접 구현
# ------------------------------------------------------------
def find_hottest_day_manual(temps):
    hottest = temps[0]      # 0이 아니라 '첫 번째 실제 값'으로 시작
    hottest_idx = 0
    idx = 0
    for temp in temps:
        if temp > hottest:  # >= 가 아니라 > 여야 먼저 나온 것이 남는다
            hottest = temp
            hottest_idx = idx
        idx += 1
    return hottest_idx


# 참고: enumerate 사용 버전 (허용 시)
def find_hottest_day_enumerate(temps):
    hottest = temps[0]
    hottest_idx = 0
    for idx, temp in enumerate(temps):
        if temp > hottest:
            hottest = temp
            hottest_idx = idx
    return hottest_idx


find_hottest_day = find_hottest_day_manual


'''
[모범 설계 주석 ]
------------------------------------------------------------------------
0. [시작값을 무엇으로 둘 것인가] 0이 아니라 temps[0](첫 번째 기온)으로 둔다.
   [왜]     0으로 두면 '아직 아무 기온도 못 봤는데 0도를 이미 본 것'처럼
            취급된다. 예시_03([-5, -12, -3, -8])은 모든 값이 0보다 작아서
            if temp > hottest 가 한 번도 참이 되지 않고, 인덱스가 0인 채로
            반환되어 오답(0)이 나온다.
            첫 번째 값을 잠정 1등으로 두면 '실제로 존재하는 값'끼리만
            비교하게 되므로 음수여도 안전하다.
            1번, 2번에서 0이었던 건 덧셈의 시작이 0이기 때문이지,
            '모든 시작값이 0'이라는 규칙이 아니었다.

1. [무엇을] hottest_idx도 0으로 함께 둔다.
   [왜]     잠정 1등이 첫 번째 값이므로, 그 위치도 0번이어야 짝이 맞는다.
            값만 추적하고 위치를 안 들고 있으면 마지막에 답을 못 만든다.

2. [무엇을] temps를 돌면서 현재 값과 hottest를 비교한다.
   [왜]     최댓값은 한 번에 알 수 없고, 끝까지 비교해 봐야 확정된다.

3. [무엇을] 더 크면 hottest와 hottest_idx를 함께 갱신한다.
   [왜]     둘 중 하나만 갱신하면 값과 위치가 어긋나 엉뚱한 인덱스가 남는다.

4. [동점 처리] 비교 연산자를 >= 가 아니라 > 로 쓴다.
   [왜]     >= 로 쓰면 같은 값이 나올 때마다 갱신되어 '마지막' 인덱스가
            남는다. 예시_01의 기댓값은 1(먼저 나온 25)이므로 > 가 맞다.
------------------------------------------------------------------------


[자주 나오는 오답 패턴]
------------------------------------------------------------------------
(1) hottest = 0 으로 시작                    ★ 이 문제의 핵심 오답
    => [21, 25, 25, 19] 는 통과, [-5, -12, -3, -8] 에서 0 반환 (기댓값 2)
    => 예시 하나만 돌려보고 넘어가는 습관까지 함께 잡을 수 있는 지점.

(2) >= 사용
    => [21, 25, 25, 19] 에서 2 반환 (기댓값 1). 동점 조건 미확인.

(3) 값만 반환
    return hottest                          # 25 반환 (기댓값 1)
    => 지문을 끝까지 안 읽음. '무엇을 반환하는가'를 신호어 단계에서
       확인했다면 나오지 않을 실수.

(4) 인덱스 갱신 누락
    if temp > hottest:
        hottest = temp                      # hottest_idx 갱신 안 함 => 0 반환
    => 값과 위치를 '한 쌍'으로 다루는 감각 부재.

(5) hottest = temps[0] 인데 idx는 1부터 시작
    => 첫 원소를 두 번 비교하게 되지만 결과에는 영향 없음. 감점 없음.
       다만 손 추적표를 시키면 본인이 어색함을 발견하게 된다.
------------------------------------------------------------------------
'''

# ---- 검증 ----
print(find_hottest_day([21, 25, 25, 19]))     # 1
print(find_hottest_day([30]))                 # 0
print(find_hottest_day([-5, -12, -3, -8]))    # 2

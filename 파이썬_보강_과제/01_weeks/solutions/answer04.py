'''
문제 04 정답 및 해설 - filter_low_stock                  [골격 ④ 필터링]
========================================================================
[출제 의도]
  결과가 '숫자'가 아니라 '리스트'인 첫 문제. 시작값이 0도 첫 원소도 아닌
  빈 리스트여야 하는 이유를 스스로 말하게 하는 것이 목적이다.
  세 번째 시작값 유형을 만나면서 '시작값은 결과의 모양을 따라간다'는
  일반 원리로 승격시킬 수 있다.

  또한 튜플 언패킹(name, stock)이 처음 나온다. 실제 1회차 평가 문제 09
  (manage_inventory)가 (품목명, 변화량) 튜플 리스트를 다뤘으므로,
  그 구조에 미리 노출시키는 의미도 있다.
========================================================================
'''

# ------------------------------------------------------------
# [기본 9점] 리스트 컴프리헨션 사용
# ------------------------------------------------------------
def filter_low_stock_builtin(items, threshold):
    return [name for name, stock in items if stock < threshold]


# ------------------------------------------------------------
# [가산 12점] 컴프리헨션 / filter 미사용, 반복문 직접 구현
# ------------------------------------------------------------
def filter_low_stock_manual(items, threshold):
    result = []
    for item in items:
        name = item[0]
        stock = item[1]
        if stock < threshold:
            result.append(name)
    return result


# 참고: 튜플 언패킹 버전 (동일 점수)
def filter_low_stock_unpack(items, threshold):
    result = []
    for name, stock in items:
        if stock < threshold:
            result.append(name)
    return result


filter_low_stock = filter_low_stock_manual


'''
[모범 설계 주석 - 기준 샘플]
------------------------------------------------------------------------
0. [시작값을 무엇으로 둘 것인가] 빈 리스트 []로 시작한다.
   [왜]     이 문제가 최종적으로 반환해야 하는 것이 리스트이기 때문.
            결과가 숫자면 0에서, 리스트면 []에서 시작하는 것이 자연스럽다.
            조건에 맞는 상품이 하나도 없으면 아무것도 안 담긴 채 []가 그대로
            반환되는데, 예시_02의 기댓값이 []이므로 이 초기값이 맞다.
            0으로 시작하면 append를 쓸 수 없다(숫자에는 담을 수 없다).

1. [무엇을] items를 for로 돌면서 상품명과 재고를 각각 꺼낸다.
   [왜]     원소가 튜플이라 값이 두 개 들어 있다. 판정에 쓰는 건 재고이고
            결과에 담는 건 상품명이라 둘을 분리해서 다뤄야 한다.

2. [무엇을] 재고가 기준 미만인지 if로 판정한다.
   [왜]     '미만'이므로 < 를 쓴다. <= 를 쓰면 기준과 같은 값까지 포함되어
            예시_03에서 pen(5)이 잘못 들어간다.

3. [무엇을] 조건이 참이면 result에 상품명만 append 한다.
   [왜]     반환해야 하는 건 이름 리스트지 (이름, 재고) 튜플 리스트가 아니다.
            item 전체를 append 하면 형식이 달라 오답 처리된다.

4. [무엇을] 앞에서부터 순서대로 돌며 append 한다.
   [왜]     append는 뒤에 붙이므로, 앞에서부터 돌면 원래 순서가 자동으로
            유지된다. 별도의 정렬은 필요 없다.
------------------------------------------------------------------------


[자주 나오는 오답 패턴]
------------------------------------------------------------------------
(1) result = 0 으로 시작
    => AttributeError. 시작값을 '결과의 모양'이 아니라 습관으로 정한 경우.
       1~3번을 기계적으로 따라한 학생이 여기서 걸린다.

(2) <= 사용
    => 예시_03에서 ['pen', 'note'] 반환 (기댓값 ['note']).
       '미만/이하/초과/이상'을 부등호로 옮기는 훈련이 필요하다는 신호.

(3) result.append(item)
    => [('pen', 3), ('eraser', 1)] 반환. 형식 불일치로 평가에서는 오답.
       실제 평가 유의사항 10번(요구 형식과 다른 반환은 오답)과 직결.

(4) result = result + name
    => 문자열이 한 글자씩 쪼개져 들어가거나 TypeError.
       append와 + 의 차이를 설명할 지점.

(5) 반복문 안에서 return
    => 첫 조건 만족 시 ['pen']만 반환.

(6) item[0]과 item[1]을 반대로 사용
    => TypeError 또는 엉뚱한 결과. 손 추적표를 쓰면 즉시 발견된다.
------------------------------------------------------------------------
'''

# ---- 검증 ----
print(filter_low_stock([('pen', 3), ('note', 10), ('eraser', 1)], 5))  # ['pen', 'eraser']
print(filter_low_stock([('pen', 8), ('note', 10)], 5))                 # []
print(filter_low_stock([('pen', 5), ('note', 4)], 5))                  # ['note']

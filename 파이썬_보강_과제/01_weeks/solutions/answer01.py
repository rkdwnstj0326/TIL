'''
문제 01 정답 및 해설 - sum_order_total                     
========================================================================
[출제 의도]
  누적 골격의 원형. 시작값 0의 근거를 언어화할 수 있는지가 유일한 관문.
  이 문제 자체는 전원이 풀 수 있어야 하며, 못 푸는 학생은 유형 ②(눈으로만
  공부) 이전에 반복문 문법 자체를 다시 봐야 한다.
========================================================================
'''

# ------------------------------------------------------------
# [기본 9점] 제한 내장 함수(sum) 사용
# ------------------------------------------------------------
def sum_order_total_builtin(orders):
    return sum(orders)


# ------------------------------------------------------------
# [가산 12점] sum 미사용, 반복문 직접 구현
# ------------------------------------------------------------
def sum_order_total_manual(orders):
    total = 0
    for price in orders:
        total += price
    return total


sum_order_total = sum_order_total_manual


'''
[모범 설계 주석]
------------------------------------------------------------------------
1. [무엇을] total 변수를 0으로 만들고 시작한다.
   [왜]     아직 아무것도 더하지 않은 상태를 숫자로 표현하면 0이기 때문.
            1로 시작하면 실제 합보다 항상 1이 커진다.
            또 주문이 한 건도 없으면 반복문이 한 번도 돌지 않아 0이 그대로
            반환되는데, 예시_03의 기댓값이 0이므로 이 초기값이 맞다.

2. [무엇을] orders를 for로 하나씩 꺼낸다.
   [왜]     '전체 주문 금액'을 다뤄야 하는데 주문이 몇 건인지 미리 알 수 없다.
            개수를 몰라도 끝까지 도는 for가 이 상황에 맞다.

3. [무엇을] 꺼낸 값을 total에 더해서 total을 갱신한다.
   [왜]     total은 '지금까지의 합'을 계속 들고 있는 그릇이라서,
            매 회차마다 갱신해야 마지막 회차 후에 전체 합이 남는다.
            total = price 로 쓰면 덮어써져서 마지막 값만 남는다.

4. [무엇을] 반복이 끝난 뒤 total을 반환한다.
   [왜]     반복문 안에서 return하면 첫 회차에 함수가 끝나버린다.
            '모두' 더한 결과가 필요하므로 반복이 끝난 뒤여야 한다.
------------------------------------------------------------------------


[자주 나오는 오답 패턴]
------------------------------------------------------------------------
(1) total 초기화 누락
    for price in orders:
        total += price          # NameError
    => 그릇을 만들기 전에 담으려 한 것. '시작점 못 찾음' 증상의 실체.

(2) return 위치가 반복문 안
    for price in orders:
        total += price
        return total            # 첫 원소만 반환 (12000)
    => 들여쓰기가 곧 실행 시점이라는 감각 부재. 손 추적표로 교정.

(3) 갱신이 아니라 덮어쓰기
    total = price               # 마지막 값(30000)만 남음
    => += 의 의미를 '더하기'가 아니라 '대입'으로 이해하고 있는 경우.

(4) 빈 리스트 미고려
    total = orders[0] 로 시작    # IndexError
    => 3번 문제의 올바른 방식을 여기에 잘못 적용한 케이스.
       두 문제를 비교시키면 '왜 다른가'를 스스로 설명하게 된다.
------------------------------------------------------------------------
'''

# ---- 검증 ----
print(sum_order_total([12000, 8500, 30000]))   # 50500
print(sum_order_total([7000]))                 # 7000
print(sum_order_total([]))                     # 0

def find_hottest_day(temps):
    high = temps[0]         # 가장 높은 기온을 찾아야 한다. 그러기 위해서는 비교할 기준이 필요함. 현재 최고 기온은 일단 첫번재 값 21이라고 해두자 라고 하고 시작
    high_index = 0          # 문제에서 원하는 답이 기온자체가 아닌 인덱스이기 때문에 필요
    for i, temp in enumerate(temps): #      (i:인덱스. temp:값)이렇게 받는다는 뜻
        if temp > high:     # 지금 꺼낸 기온 temp가 지금까지의 최고 기온 high보다 크냐는 뜻
            high = temp     # if문이 참이 되면 high=temp여서 갱신됨
            high_index = i  # 갱신된 high의 인덱스를 저장하기 위해서 사용

    return high_index



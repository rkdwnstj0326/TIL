# ============================================================
# [1] 신호어 찾기  (코드를 치기 전에 작성)
# ============================================================
# 지문에서 찾은 신호어 : 전체 주문 금액의 총합
# 선택한 골격         : 누적
# 그렇게 판단한 이유   : 전체 주문 금액의 총합을 구하라는 것은 계속 누적해서 더해야하므로 '누적'골격을 써야한다.


# ============================================================
# [2] 설계 - 무엇을 / 왜
# ------------------------------------------------------------
# [왜] 칸에 '그냥', '원래', '강의에서'는 쓸 수 없습니다.
# 특히 시작값을 정한 근거는 반드시 본인 언어로 설명하세요.
# ============================================================
# 1. [무엇을] total변수를 0으로 만든다.
#    [왜] 값을 누적해서 더해야하기 때문에 0에서부터 값을 더해가기 위해서 total을 0으로 만든다
#
# 2. [무엇을] for문을 사용해서 입력값을 하나씩 꺼낸다
#    [왜] 누적 값을 알아야 하기 때문에, 리스트에 있는 값을 차곡차곡 더해야한다. 이때 반복문을 사용해서 하나씩 꺼내야함
#
# 3. [무엇을] 0인 total값에 계속 더한다
#    [왜] 누적 값을 구해야 하기 때문. total은 현재 0이기 때문에 여기에 계속해서 매출을 더해야한다.


def sum_order_total(orders):
    total = 0
    for order in orders:
        total = total + order
    return(total)

# ============================================================
# [3] 손 추적표  (실행 전에 작성)
# ------------------------------------------------------------
# 입력 [12000, 8500, 30000] 기준으로 예측해서 적으세요.
# ============================================================
# 회차 | 꺼낸 값 | total
# 1   |  12000 | 12000
# 2   |   8500 | 20500
# 3   |  30000 | 50500


# ============================================================
# [4] 회고
# ============================================================
# 막힌 지점            :   total = total + order / 처음에 total = orders + 1 라고 써서 막혔음..
# 30분 규칙 사용       : (예)
# 예측과 실제가 달랐던 곳 :


# ---- 확인용 출력 (수정하지 마세요) ----
print(sum_order_total([12000, 8500, 30000]))
print(sum_order_total([7000]))
print(sum_order_total([]))

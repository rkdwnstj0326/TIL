#2트 [지피티돌림-내가 쓴 코드를 기반으로]
def filter_low_stock(items, threshold):
    result = [] # 조건에 맞는 상품을 전부 모아야 해서 빈 리스트를 만들어야 함,,

    for item in items:
        if threshold > item[1]:
            result.append(item[0]) #조건에 맞으면 바로 반환하지 않고, result에 상품 이름을 다 모으기 위해서 append사용

    return result



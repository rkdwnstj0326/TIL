#[2트 - 지피티]
def sum_sales_by_category(records):

    result = {}

    for category, price in records: # 돌릴 때 마다 하나의 튜플을 받아줌. 그 튜블의 값이 자동으로 카테고리랑 price에 나눠짐

        if category in result: #category가 result 딕셔너리에 지금 이미 들어가 있는가를 알아보기 위해서
            result[category] = result[category] + price #total = total+score ->이런거랑 원리는 똑같다. 대신, coffee라는 누적 공간에 계속 더하는 것일 뿐임

        else: # category가 처음 등장한 경우
            result[category] = price

    return result
        



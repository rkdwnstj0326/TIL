# [이해가 안가서 일단 지피티 돌렸습니다..]
def find_all_hottest_days(temps):
    high = temps[0] #지금까지 본 기온 중 가장 높은 기온 값을 저장
    result = [0] # 최고 기온이 나온 인덱스들을 저장하기 위해서 리스트 지정

    for i in range(1, len(temps)): #인덱스 1부터 마지막 인덱스까지 하나씩 확인하겠다. 왜 1부터? 0번은 이미 위에서 처리햇기 때문
        if temps[i] > high: #지금 내가 확인한기온이 지금까지의 최고 기온보다 더 높은지 확인한다.
            high = temps[i] #더 높은 기온이 나와서 최고 기온을 새 값으로 바꾸기 위함.
            result = [i] #더 높은 기온이 새로 나왔다는건 전에 저장했던 인덱스가 이제 정답이아님을 뜻함.

        elif temps[i] == high: #현재의 기온이 지금까지의 최고 기온과 똑같은 경우를 확인
            result.append(i)

    return result



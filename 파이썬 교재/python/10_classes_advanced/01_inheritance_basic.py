# =============================================================
# 상속 (Inheritance) - 기존 클래스의 기능을 물려받기
# - 문법: class 자식(부모):
# - 자식 클래스는 부모의 속성과 메서드를 그대로 사용할 수 있음
# =============================================================


class Animal:
    def eat(self):
        print('먹는 중')


# Dog는 Animal을 상속 => Animal의 모든 기능을 물려받음
class Dog(Animal):
    def bark(self):
        print('멍멍')
        


my_dog = Dog()

# =============================================================
# my_dog는 Dog로 만들었지만, 부모 Animal의 메서드도 쓸 수 있음
# - bark() : Dog 자신이 정의한 메서드
# - eat()  : 물려받은 부모 Animal의 메서드
#   => 코드를 중복해서 쓰지 않고 재사용하는 것이 상속의 핵심 이점
# =============================================================

my_dog.bark()  # 멍멍

# 부모 클래스(Animal) 메서드 사용 가능
my_dog.eat()  # 먹는 중

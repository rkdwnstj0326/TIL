# =============================================================
# [심화] MRO (Method Resolution Order) - 메서드 탐색 순서
# - 다중 상속에서 파이썬이 '어떤 순서로' 부모를 찾는지를 정한 규칙
# - super()가 "다음으로 넘길 클래스"를 결정하는 기준이 바로 이 순서
# - 이 예제는 다이아몬드 구조(마름모 상속)로 MRO를 확인
#
#        A          A를 B와 C가 각각 상속하고,
#       / \         D가 다시 B와 C를 함께 상속하는 구조
#      B   C        => "A로 가는 길이 두 갈래"라 순서 규칙이 꼭 필요
#       \ /
#        D
# =============================================================


class A:
    def __init__(self):
        print('A Constructor')


class B(A):
    def __init__(self):
        super().__init__()
        print('B Constructor')


class C(A):
    def __init__(self):
        super().__init__()
        print('C Constructor')


class D(B, C):
    def __init__(self):
        super().__init__()
        print('D Constructor')


# =============================================================
# D.mro() / D.__mro__ - 탐색 순서를 직접 확인
# - 결과: D -> B -> C -> A -> object
#   (object는 모든 클래스의 최상위 부모)
# - 규칙 요약: 자식이 먼저, 같은 단계에서는 상속에 쓴 순서(B, C)대로,
#             공통 조상 A는 그 아래 자식들을 모두 거친 뒤 '마지막에 한 번'
#   => A가 두 번 실행되지 않도록 보장하는 것이 MRO의 핵심 목적
# =============================================================

# [<class '__main__.D'>, <class '__main__.B'>, <class '__main__.C'>, <class '__main__.A'>, <class 'object'>]
print(D.mro())

# (<class '__main__.D'>, <class '__main__.B'>, <class '__main__.C'>, <class '__main__.A'>, <class 'object'>)
print(D.__mro__)

# =============================================================
# D()를 실제로 생성하면 출력 순서가 흥미로움
# - 각 __init__이 super().__init__()를 먼저 부르고 자기 이름을 출력하므로,
#   호출은 D->B->C->A 순으로 '타고 내려가고',
#   출력(print)은 가장 깊은 A부터 '거슬러 올라오며' 찍힘
#   => 실제 출력: A => C => B => D
# - super()를 '직계 부모'로만 이해하면 B 다음 A가 나올 것 같지만,
#   MRO 덕분에 B의 super()가 C를 가리켜 C가 먼저 실행됨
#   (다중 상속에서 super()가 직계 부모가 아니라는 06번의 결론과 연결됨)

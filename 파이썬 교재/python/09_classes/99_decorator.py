# =============================================================
# [심화] 데코레이터 (Decorator)
# - 기존 함수를 '수정하지 않고' 기능을 덧입히는 문법
# - 앞서 본 @classmethod, @staticmethod가 바로 데코레이터였음
# - @ 표시 하나로 함수를 다른 함수로 감싸(wrapping) 줌
# =============================================================

# =============================================================
# [1] 데코레이터 정의 - '함수를 받아 함수를 돌려주는' 함수
# - my_decorator는 func(원본 함수)를 받아,
#   그 앞뒤에 동작을 추가한 wrapper를 만들어 반환함
# - 원본 func는 wrapper 안에서 그대로 호출됨
#   => 원본을 건드리지 않고 '전/후 작업'만 끼워 넣는 구조
# =============================================================

# 데코레이터 정의
def my_decorator(func):
    def wrapper():
        # 함수 실행 전에 수행할 작업
        print('함수 실행 전')
        # 원본 함수 호출
        result = func()
        # 함수 실행 후에 수행할 작업
        print('함수 실행 후')
        return result

    return wrapper


# =============================================================
# [2] 데코레이터 적용 - @ 표기
# - @my_decorator 는 아래와 완전히 같은 의미의 축약형
#     my_function = my_decorator(my_function)
# - 즉 my_function은 이제 wrapper로 교체된 상태
#   => 호출하면 '실행 전 => 원본 => 실행 후' 순서로 동작
# =============================================================

# 데코레이터 활용 예시
@my_decorator
def my_function():
    print('원본 함수 실행')


my_function()

"""
함수 실행 전
원본 함수 실행
함수 실행 후
"""

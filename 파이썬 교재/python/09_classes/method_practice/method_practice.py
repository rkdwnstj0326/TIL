# =============================================================
# [종합 실습] 은행 계좌 클래스
# - 지금까지 배운 세 가지 메서드를 한 클래스에 모아 비교
#   ① 인스턴스 메서드 : 특정 계좌의 잔액을 다룸       (self)
#   ② 클래스 메서드   : 모든 계좌 공통의 이자율을 다룸 (cls)
#   ③ 정적 메서드     : 계좌와 무관한 순수 계산        (인자만)
# - "이 작업이 무엇에 속한 일인가"를 기준으로 메서드 종류를 고름
# =============================================================

# 메서드 활용
# 입출금이 가능한 은행 계좌 클래스 만들기
# 은행 계좌를 모델링하는 클래스를 만들고, 입출금 기능(메서드)를 구현


class BankAccount:
    interest_rate = 0.02  # 이자율 (클래스 변수: 모든 계좌 공통)

    def __init__(self, owner, balance=0):
        self.owner = owner  # 계좌 소유자 (인스턴스마다 다름)
        self.balance = balance  # 초기 잔액 (인스턴스마다 다름)

    # -------------------------------------------------------------
    # 입금 - '이 계좌'의 잔액을 바꾸므로 인스턴스 메서드 (self)
    # -------------------------------------------------------------
    def deposit(self, amount):
        self.balance += amount

    # -------------------------------------------------------------
    # 출금 - 역시 '이 계좌'의 잔액을 다루므로 인스턴스 메서드
    # 잔액이 부족하면 출금하지 않고 안내
    # -------------------------------------------------------------
    def withdraw(self, amount):
        if self.balance >= amount:
            self.balance -= amount
        else:
            print('잔액 부족!')

    # -------------------------------------------------------------
    # 이자율 설정 - 특정 계좌가 아니라 '모든 계좌 공통'의 값을 바꿈
    # => 클래스 변수를 다루므로 클래스 메서드 (cls)
    # -------------------------------------------------------------
    @classmethod
    def set_interest_rate(cls, rate):
        cls.interest_rate = rate

    # -------------------------------------------------------------
    # 금액 검증 - 계좌 정보와 전혀 무관한 순수 계산 (양수인가?)
    # => self도 cls도 필요 없으므로 정적 메서드
    # -------------------------------------------------------------
    @staticmethod
    def is_positive(amount):
        return amount > 0


# =============================================================
# 실제 사용 - 각 메서드가 어떤 방식으로 호출되는지 비교
# =============================================================

# 계좌 개설 (인스턴스 생성)
alice_acc = BankAccount('Alice', 1000)

# 입금 및 출금 (인스턴스 메서드 호출: 인스턴스.메서드())
alice_acc.deposit(500)
alice_acc.withdraw(200)

# 잔액 확인 (인스턴스 변수 참조)
print(alice_acc.balance)  # 1300

# 이자율 변경 (클래스 메서드 호출: 클래스.메서드())
BankAccount.set_interest_rate(0.03)
print(BankAccount.interest_rate)  # 0.03

# 잔액이 양수인지 확인 (정적 메서드 호출: 클래스.메서드())
print(BankAccount.is_positive(alice_acc.balance))  # True

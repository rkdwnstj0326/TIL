# =============================================================
# 정적 메서드 (Static Method)
# - 클래스에 소속만 되어 있을 뿐, 인스턴스나 클래스의 상태와 무관
# - @staticmethod 데코레이터를 붙이며, self도 cls도 받지 않음
# - 즉 self/cls가 필요 없는 '순수한 기능'을 클래스 안에 묶어둘 때 사용
#   => 계산기의 덧셈처럼, 어떤 인스턴스의 데이터도 건드리지 않는 작업
# =============================================================

class MathUtils:
    # 정적 메서드
    # 클래스나 인스턴스에 의존하지 않고 독립적으로 동작
    # 정적 메서드는 클래스나 인스턴스의 상태를 변경하지 않음
    @staticmethod
    def add(a, b):
        return a + b


# =============================================================
# 인스턴스를 만들 필요 없이 클래스 이름으로 바로 호출
# - MathUtils.add(3, 5) => 8
# - 그냥 함수처럼 동작하지만, 관련 기능을 클래스로 묶어 관리하는 이점
# =============================================================

# 정적 메서드 호출
print(MathUtils.add(3, 5))  # 8

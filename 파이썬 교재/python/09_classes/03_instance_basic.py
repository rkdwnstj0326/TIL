# =============================================================
# 인스턴스(Instance) - 설계도(클래스)로 찍어낸 실제 객체
# - 하나의 클래스로 서로 다른 인스턴스를 여러 개 만들 수 있음
# - 각 인스턴스는 자기만의 속성 값을 '독립적으로' 가짐
# =============================================================

class Person:
    def __init__(self, name, age):
        self.name = name  # 인스턴스 속성
        self.age = age  # 인스턴스 속성

    def introduce(self):
        print(f'안녕하세요. 저는 {self.name}, 나이는 {self.age}살입니다.')


# =============================================================
# 같은 Person 설계도로 만들었지만 p1과 p2는 서로 다른 객체
# - p1.introduce()는 p1의 name(Alice)을,
#   p2.introduce()는 p2의 name(Bella)을 사용
# - 즉 self가 '호출한 바로 그 인스턴스'를 가리키기 때문
#   => 붕어빵 틀은 하나지만, 각 붕어빵의 속은 다를 수 있음
# =============================================================

p1 = Person('Alice', 25)
p1.introduce()  # "안녕하세요. 저는 Alice, 나이는 25살입니다."

p2 = Person('Bella', 30)
p2.introduce()  # "안녕하세요. 저는 Bella, 나이는 30살입니다."

# =============================================================
# 생성자 메서드 (Constructor, __init__)
# - 인스턴스가 만들어지는 순간 '자동으로 한 번' 호출됨
# - 주된 역할: 인스턴스의 초기 속성값을 설정 (초기화)
# - 앞뒤로 언더바 2개(__)가 붙은 메서드는 파이썬이 특별하게 다룸
#   (매직 메서드 / 던더 메서드, 99_magic_method.py에서 학습)
# =============================================================

class Person:
    def __init__(self, name):
        self.name = name

    def greeting(self):
        print(f'안녕하세요 {self.name}입니다.')


# =============================================================
# Person('지민') 호출 시 내부에서 일어나는 일
# - 빈 인스턴스가 만들어지고, 곧바로 __init__(self, '지민')이 실행됨
#   => self.name에 '지민'이 저장됨
# =============================================================

person1 = Person('지민')  # 인스턴스가 생성되었습니다.

# =============================================================
# 아래 두 줄은 '완전히 같은 동작'
# - person1.greeting()      : 파이썬이 self 자리에 person1을 자동 전달
# - Person.greeting(person1): self를 직접 넘겨 호출 (내부 원리를 보여줌)
#   => 점(.) 호출은 결국 '클래스의 메서드에 인스턴스를 넘기는 것'
# =============================================================

person1.greeting()  # 안녕하세요. 지민입니다.
Person.greeting(person1)  # 안녕하세요. 지민입니다.
print(person1.name)  # 지민

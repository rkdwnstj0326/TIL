# =============================================================
# [심화] 네임스페이스와 이름 탐색 순서
# - 인스턴스로 속성에 접근하면, 파이썬은 다음 순서로 이름을 찾음
#     ① 인스턴스 자신에게 그 이름이 있는가?
#     ② 없으면 => 클래스에 있는가? (클래스 변수)
# - 이 '인스턴스 먼저, 없으면 클래스' 순서가 이 파일의 핵심
# =============================================================

class Person:
    name = 'unknown'  # 클래스 변수

    def talk(self):
        # self.name => 먼저 인스턴스에서 찾고, 없으면 클래스에서 찾음
        print(self.name)


# =============================================================
# [1] p1은 자기만의 name이 없음 => 클래스 변수 'unknown'을 참조
# =============================================================

# p1 인스턴스 생성
p1 = Person()
p1.talk()  # unknown

# =============================================================
# [2] p2도 아직 자기 name이 없는 상태 => 역시 클래스 변수 참조
# =============================================================

# p2 인스턴스 생성 (인스턴스 변수 설정 전)
p2 = Person()
p2.talk()  # unknown

# =============================================================
# [3] p2.name = 'Kim' => p2에게만 인스턴스 변수 name이 생김
# - 이제 p2.talk()는 ① 단계에서 자기 것을 찾으므로 'Kim'
# =============================================================

# p2 인스턴스 변수 설정 후
p2.name = 'Kim'
p2.talk()  # Kim

# =============================================================
# [4] 중요: p2에 값을 넣어도 클래스 변수와 p1은 그대로
# - Person.name  => 여전히 'unknown' (클래스 변수는 안 바뀜)
# - p2.name      => 'Kim' (p2만의 인스턴스 변수)
# - p1.name      => 'unknown' (p1은 여전히 클래스 변수 참조)
#   => 인스턴스는 서로 독립적이며, 한 인스턴스의 변경이
#      클래스나 다른 인스턴스에 영향을 주지 않음
# =============================================================

# 클래스 변수 name 값이 변경된 것이 아님(클래스 변수 name은 여전히 'unknown')
print(Person.name)  # unknown
# p2의 name은 인스턴스 변수로 설정된 값
print(p2.name)  # Kim
# 인스턴스는 독립적이므로 p1의 name은 여전히 'unknown'
print(p1.name)  # unknown

# =============================================================
# 프로그래밍 패러다임 - 같은 문제를 바라보는 두 가지 방식
# - 절차 지향: 데이터(변수)와 기능(함수)을 '따로' 두고 조합
# - 객체 지향: 데이터와 기능을 '하나의 객체'로 묶어서 다룸
# - 지금까지 써온 방식이 절차 지향, 이번 단원부터가 객체 지향
# =============================================================

# =============================================================
# [1] 절차 지향 사고
# - name, age라는 데이터와 introduce라는 기능이 서로 분리되어 있음
# - 함수를 호출할 때마다 필요한 데이터를 '직접 전달'해야 함
#   => 데이터가 늘어날수록 무엇을 넘겨야 하는지 관리가 번거로워짐
# =============================================================

# 절차 지향 사고
# 예: 변수와 함수를 별개로 다룸
name = 'Alice'
age = 25


def introduce(name, age):
    print(f'안녕하세요, {name}입니다. 나이는 {age}살입니다.')


introduce(name, age)


# =============================================================
# [2] 객체 지향 사고
# - Person이라는 '틀(클래스)' 안에 데이터(name, age)와
#   기능(introduce)을 함께 담음
# - alice 객체는 자기 데이터를 이미 갖고 있으므로,
#   introduce()에 아무것도 넘기지 않아도 스스로 소개함
#   => "데이터를 넘긴다"에서 "객체에게 시킨다"로 사고가 바뀜
# - class, __init__, self는 다음 파일부터 하나씩 자세히 학습
# =============================================================


# 객체 지향 사고
# 예: 사람(객체) 안에 name, age와 이와 관련된 기능(메서드) 포함
class Person:
    def __init__(self, name, age):
        self.name = name
        self.age = age

    def introduce(self):
        print(f'안녕하세요, {self.name}입니다. 나이는 {self.age}살입니다.')


alice = Person('Alice', 25)
alice.introduce()


# =============================================================
# 클래스 변수와 인스턴스 변수의 관계 - 값을 '덮어쓸' 때 무슨 일이?
# - 핵심: 인스턴스에 같은 이름의 변수를 만들면,
#         그 인스턴스는 클래스 변수 대신 자기 것을 먼저 봄
# - 하지만 클래스 변수 자체는 바뀌지 않고, 다른 인스턴스도 영향 없음
# =============================================================

class Circle:
    pi = 3.14  # 클래스 변수 (모든 인스턴스 공유)

    def __init__(self, radius):
        self.radius = radius  # 인스턴스 변수


# 인스턴스 생성
c1 = Circle(5)
c2 = Circle(10)

# 인스턴스 변수(속성) 접근
print(c1.radius)  # 5
print(c2.radius)  # 10

# =============================================================
# c1.pi = 100 의 의미
# - 클래스 변수 pi를 바꾸는 게 아니라,
#   c1에게만 있는 '새로운 인스턴스 변수 pi'를 만드는 것
# - 이후 c1.pi는 클래스 변수가 아니라 자기 것(100)을 먼저 봄
#   => 이름은 같지만 저장 위치가 다름
# =============================================================

# 인스턴스 c1의 인스턴스 변수 pi를 생성
c1.pi = 100

# 인스턴스 c1의 인스턴스 변수 pi를 출력
print(c1.pi)  # 100

# =============================================================
# 클래스 변수 자체는 그대로 3.14
# - Circle.pi로 직접 확인하면 원본은 변하지 않았음을 알 수 있음
# - c2는 자기만의 pi를 만든 적이 없으므로 여전히 클래스 변수를 참조
#   => 한 인스턴스의 변경이 다른 인스턴스에 영향을 주지 않음
# =============================================================

# 클래스 변수 접근
print(Circle.pi)  # 3.14

# 반면 인스턴스 c2는 인스턴스 변수 pi가 없으므로 클래스 변수 pi를 참조
print(c2.pi)  # 3.14

# =============================================================
# "사실 우리는 이미 클래스를 써왔다"
# - 지금까지 다룬 문자열, 리스트도 전부 '클래스로 만든 인스턴스'였음
# - .split(), .append() 같은 메서드를 쓸 수 있었던 이유가 바로 이것
# =============================================================

# =============================================================
# [1] 내가 만든 클래스의 인스턴스
# - Singer 클래스로 만든 iu는 Singer의 인스턴스
# - type()으로 확인하면 어떤 클래스에서 나왔는지 보임
#   => <class '__main__.Singer'>  (__main__은 지금 실행 중인 파일)
# =============================================================


class Singer:
    def sing(self):
        return 'lalala'


iu = Singer()
print(iu.sing())
print(type(iu))




# =============================================================
# [2] 파이썬 기본 자료형도 사실은 클래스
# - 'Alice'는 str 클래스의 인스턴스
# - [1, 2, 3]은 list 클래스의 인스턴스
#   => type()으로 확인하면 <class 'str'>, <class 'list'>
# =============================================================

# 문자열 변수 name은 (정확히는 'Alice')는 str 클래스의 인스턴스
name = 'Alice'
print(type(name))  # <class 'str'>

data = [1, 2, 3]
print(type(data))  # <class 'list'>

# =============================================================
# [3] 그동안 메서드를 쓸 수 있었던 진짜 이유
# - name.split()이 되는 건, split()이 str 클래스 안에 정의돼 있어서
# - data.append()가 되는 건, append()가 list 클래스 안에 있어서
#   => 우리가 배운 '자료형별 메서드'가 곧 '그 클래스의 메서드'였음
# - 결론: 파이썬의 모든 것은 객체(클래스의 인스턴스)
# =============================================================

# 데이터들이 메서드를 호출할수 있었던 이유
# 문자열 name이 사용할 수 있는 메서드인 split()은 클래스 str에 정의되어 있음
# 리스트 data가 사용할 수 있는 메서드인 append()는 클래스 list에 정의되어 있음

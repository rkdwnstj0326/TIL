# =============================================================
# try 구문의 전체 형태 - else와 finally
# - try     : 시도할 코드
# - except  : 예외가 발생했을 때 실행
# - else    : 예외가 '발생하지 않았을 때만' 실행
# - finally : 예외 여부와 상관없이 '항상' 실행
#
# [실행 주의] input()으로 입력을 기다립니다. 터미널에서 실행하세요.
# =============================================================

try:
    # 에러가 날 수 있는 코드
    x = int(input('숫자를 입력하세요: '))
    y = 10 / x
except ZeroDivisionError:
    # x가 0일 때
    print('0으로 나눌 수 없습니다.')
except ValueError:
    # 숫자가 아닌 값을 입력했을 때
    print('유효한 숫자가 아닙니다.')
else:
    # =========================================================
    # else: try가 '무사히' 끝났을 때만 실행
    # - 결과 출력처럼 '성공했을 때만 할 일'을 여기 둠
    # - 왜 try 안에 안 두고 else로 빼는가?
    #   try는 에러가 날 수 있는 부분만 최소한으로 두는 것이 좋음
    #   (엉뚱한 곳의 에러까지 except가 잡아버리는 것을 막기 위해)
    # =========================================================
    print(f'결과: {y}')
finally:
    # =========================================================
    # finally: 성공하든 실패하든 무조건 실행
    # - 파일 닫기, 연결 해제처럼 '반드시 정리해야 할 일'에 사용
    # =========================================================
    print('프로그램이 종료되었습니다.')

# =============================================================
# [심화] EAFP vs LBYL - 예외를 다루는 두 가지 철학
# - 같은 문제(없을 수도 있는 키 접근)를 해결하는 두 접근법
# - 어느 하나가 정답은 아니며, 상황에 따라 선택
# =============================================================

my_dict = {
    'key': 'value',
}

# =============================================================
# [1] EAFP (Easier to Ask for Forgiveness than Permission)
#     "허락보다 용서가 쉽다" => 일단 해보고, 안 되면 그때 처리
# - 확인 없이 바로 접근하고, 예외가 나면 except로 대응
# - 대부분의 경우 성공한다면 더 효율적
#   => 성공 케이스에서는 조건 검사 비용이 들지 않음
# =============================================================

# EAFP (Easier to Ask for Forgiveness than Permission)
try:
    result = my_dict['key']
    print(result)
except KeyError:
    print('Key가 존재하지 않습니다.')


# =============================================================
# [2] LBYL (Look Before You Leap)
#     "돌다리도 두들겨 보고 건너라" => 미리 확인한 뒤 실행
# - if로 키의 존재 여부를 먼저 검사하고 접근
# - 다른 언어에서 익숙한 방식이며, 의도가 명시적으로 드러남
# - 주의: 확인과 실행 사이에 값이 바뀔 수 있는 상황에서는
#         EAFP가 더 안전할 때도 있음
# =============================================================

# LBYL (Look Before You Leap)
if 'key' in my_dict:
    result = my_dict['key']
    print(result)
else:
    print('Key가 존재하지 않습니다.')

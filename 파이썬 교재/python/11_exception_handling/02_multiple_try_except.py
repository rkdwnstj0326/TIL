# =============================================================
# 복수 예외 처리 - 여러 종류의 예외에 대응하기
# - 하나의 try 블록에서 여러 예외가 발생할 수 있음
#   예) int() 변환 실패(ValueError) 또는 0으로 나누기(ZeroDivisionError)
# - 대응 방식은 두 가지: 묶어서 한 번에 / 종류별로 따로
#
# [실행 주의] 두 예제 모두 input()으로 입력을 기다립니다.
#    터미널에서 실행하세요.
# =============================================================

# =============================================================
# [1] 묶어서 처리 - 여러 예외를 튜플로 묶어 같은 방식으로 대응
# - 어떤 예외가 나든 동일한 메시지로 안내하면 될 때 간결함
#   (ValueError, ZeroDivisionError) => 둘 중 무엇이 나도 여기서 처리
# =============================================================

# 복수 예외처리
try:
    num = int(input('100을 나눌 값을 입력하시오 : '))
    print(100 / num)
except None:
    print('제대로 입력해주세요.')


# =============================================================
# [2] 종류별로 따로 처리 - 예외마다 다른 안내를 주고 싶을 때
# - except를 여러 개 나열하면, 발생한 예외에 '맞는 것 하나'만 실행됨
#   ValueError       => 숫자가 아닌 입력
#   ZeroDivisionError => 0 입력
# - 맨 아래 except: (이름 없음)은 위에서 못 잡은 그 외 모든 예외를 처리
#   => '최후의 방어선' 역할
# =============================================================

try:
    num = int(input('100을 나눌 값을 입력하시오 : '))
    print(100 / num)
except ValueError:
    print('숫자를 넣어주세요.')
except ZeroDivisionError:
    print('0으로 나눌 수 없습니다.')
except:
    print('에러가 발생했습니다.')

# =============================================================
# [심화] as 키워드 - 발생한 예외 객체를 변수로 받기
# - except 예외 as 변수:  형태
# - 파이썬이 만든 '예외 객체'를 변수에 담아, 에러의 상세 내용을
#   메시지로 꺼내 쓸 수 있음
# - 어떤 예외가 왜 났는지 로그로 남길 때 유용
# =============================================================

my_list = []

try:
    # 빈 리스트의 1번 인덱스에 접근 => IndexError 발생
    number = my_list[1]
except IndexError as error:
    # error에는 예외 객체가 담김
    # print에서 문자열로 변환되며 실제 에러 메시지가 출력됨
    #   => 'list index out of range'
    # list index out of range가 발생했습니다.
    print(f'{error}가 발생했습니다.')

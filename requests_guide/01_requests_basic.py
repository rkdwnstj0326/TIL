'''
==========================================================
 requests 기본 사용법
==========================================================

 오늘 할 일은 딱 하나
   "인터넷에 있는 데이터를 파이썬으로 가져와서 꺼내 쓰기"

 사용할 주소 (연습용 공개 API, 가입도 키도 필요 없음)
   https://jsonplaceholder.typicode.com/users

 실행 방법 (가상환경에 requests가 설치되어 있다면 설치하지 않아도 됩니다.)
   $ pip install requests
   $ python 01_requests_basic.py
==========================================================
'''

# requests 는 파이썬에 기본으로 없는 외부 라이브러리입니다.
# 그래서 pip install requests 로 먼저 설치해야 import 가 됩니다.
import requests

URL = 'https://jsonplaceholder.typicode.com/users'

#URL은 상수임 -> 고정된 값이라는 뜻임. 더이상 바뀔 일 없음

# ==========================================================
# 1. 요청 보내기
# ==========================================================
print('=' * 55)
print('1. 요청 보내기')
print('=' * 55)

# 브라우저 주소창에 주소를 치는 것과 똑같은 일을,
# 파이썬 코드로 대신 시키는 것이 requests.get() 입니다.
response = requests.get(URL)
#requests.get(URL) 여기로 요청을 보내는 것? 이 return을 response에 넣는거임

print('response :', response)
print('타입     :', type(response))

# 여기서 많이들 오해합니다.
#   "response 안에 사용자 목록이 들어있겠지?"  =>  아닙니다.
#
#   requests.get()  =  택배를 시킨 것
#   response        =  도착한 '상자'  (상자지, 내용물이 아님)
#
# 내용물은 다음 단계에서 우리가 직접 꺼내야 합니다.


# ==========================================================
# 2. 상자 열어보기 - .text
# ==========================================================
print()
print('=' * 55)
print('2. 상자 열어보기 - .text')
print('=' * 55)

# 서버가 보내주는 내용물은 '언제나 글자(문자열)' 입니다.
print(response.text[:150])  # 너무 길어서 앞 150글자만 잘랐음
print('...')
print()
print('.text 의 타입 :', type(response.text))

# 글자라서, 지금 상태로는 "3번째 사람 이름" 같은 걸 꺼낼 수가 없습니다.
# 리스트처럼 생겼지만 리스트가 아니기 때문입니다.


# ==========================================================
# 3. 파이썬이 알아듣게 번역하기 - .json()
# ==========================================================
print()
print('=' * 55)
print('3. 번역하기 - .json()')
print('=' * 55)

# .json() 은 그 '글자'를 파이썬 자료형(list, dict)으로 바꿔줍니다.
#   .text   = 외국어로 온 편지 원문
#   .json() = 한국어로 번역한 결과 (이제 내용을 다룰 수 있음)
data = response.json()

print('data 의 타입 :', type(data))
print('사람 수      :', len(data))

# 이 한 줄이 오늘의 핵심입니다.
# 서버에서 받은 건 글자, 다루려면 .json()


# ==========================================================
# 4. 안이 어떻게 생겼는지 확인하기
# ==========================================================
print()
print('=' * 55)
print('4. 구조 확인하기')
print('=' * 55)

# 처음 보는 데이터는 절대 추측하지 않습니다. 두 가지만 확인하면 됩니다.
#   list  =>  len() 으로 몇 개인지
#   dict  =>  keys() 로 어떤 이름표가 붙어 있는지

first = data[0]  # 리스트의 첫 번째 => 사람 한 명 (dict)

print('첫 번째 사람의 타입 :', type(first))
print('가지고 있는 키      :', list(first.keys()))

# 구조를 그림으로 보면 이렇습니다.
#
#   data (list)
#     └─ data[0] (dict)   <- 사람 한 명
#          ├─ 'name'    : 'Leanne Graham'
#          ├─ 'email'   : 'Sincere@april.biz'
#          └─ 'address' (dict)      <- dict 안에 또 dict
#                └─ 'city' : 'Gwenborough'


# ==========================================================
# 5. 값 꺼내 쓰기
# ==========================================================
print()
print('=' * 55)
print('5. 값 꺼내 쓰기')
print('=' * 55)

# 리스트는 번호로, 딕셔너리는 키로 꺼냅니다. Step 2, 3 에서 배운 그대로입니다.
print('이름   :', first.get('name'))
print('이메일 :', first.get('email'))

# 한 단계 더 들어간 값은 바깥에서 안쪽 순서로 이어서 씁니다.
print('도시   :', first.get('address').get('city'))
#                 └ data[0]  └ 'address' 라는 dict  └ 그 안의 'city'


# ==========================================================
# 6. 전부 한 번에 보기
# ==========================================================
print()
print('=' * 55)
print('6. 반복문으로 전부 출력')
print('=' * 55)

# data 는 list 이므로 for 로 한 명씩 돌 수 있습니다.
for user in data:
    name = user.get('name')
    city = user.get('address').get('city')
    print(f'{name} / {city}')


# ==========================================================
# 정리
# ==========================================================
print()
print('=' * 55)
print('오늘 가져갈 3줄')
print('=' * 55)
print('1. requests.get(주소) 는 데이터가 아니라 "상자"를 돌려준다')
print('2. 받은 내용은 글자다. .json() 을 써야 파이썬이 알아듣는다')
print('3. 번역만 되면 그 다음은 우리가 배운 list, dict 다루기가 전부다')
